import pandas as pd

df = pd.read_csv(r"data\henan_clean.csv")
df["增速(%)"] = pd.to_numeric(df["增速(%)"], errors="coerce")

print("表有多大:", df.shape)
print()


# ------------------------------------------------------------
# 第 1 题：只改槽三（动作）
# 目标：算出 GDP 的总和
# 现在写的是 .mean()（平均），把这一处改成 .sum()（总和）
# ------------------------------------------------------------
print("第1题 GDP 总和:", df["GDP"].sum())


# ------------------------------------------------------------
# 第 2 题：只改槽二（列名）
# 目标：算出所有城市的平均增速
# 现在写的是 "GDP"，把这一处改成 "增速(%)"
# ------------------------------------------------------------
print("第2题 平均增速:", df["增速(%)"].mean())


# ------------------------------------------------------------
# 第 3 题：两个槽都要改
# 目标：找出增速最高的那个数值
# 提示：列名改成 "增速(%)"，动作改成 .max()
# ------------------------------------------------------------
print("第3题 最高增速:", df["增速(%)"].max())


# ------------------------------------------------------------
# 第 4 题：改括号里的"参数"
# 目标：按 GDP 从小到大排，只要第一行（也就是最小的那个市）
# 现在 ascending=False 是从大到小，改成 True 就是从大到小反过来
# 现在 head(3) 是前三行，改成 1
# ------------------------------------------------------------
print("第4题 GDP 最小的市:")
print(df.sort_values("GDP", ascending=True).head(1))
# ------------------------------------------------------------
# 第 5 题：自己写，没有模板
# 目标：只打印出城市的名字，不要 GDP、不要增速
# 提示：还是那三个槽。表是 df，列名是 "地区"，动作……这次不需要动作
#
# 把下面这行 print 删掉，自己写一行
# ------------------------------------------------------------
print(df["地区"])
