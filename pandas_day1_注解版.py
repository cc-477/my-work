# ------------------------------------------------------------
# 第一段：把表读进来
# ------------------------------------------------------------

import pandas as pd
# import = 把别人写好的工具箱搬进来
# pandas = 工具箱的名字（专门处理表格）
# as pd  = 给它起个外号叫 pd，以后少打字


p = r"data\henan_dirty.csv"
# p = 我给"文件路径"起了个名字。叫 a、叫 lujing 都行，只是个名字
# r"..." = 告诉 python：里面的反斜杠 \ 不用特殊处理，原样照用
#          （Windows 路径都是反斜杠，不加 r 容易报错）


df = pd.read_csv(p, header=2)
# 从里往外读：
#   p                → 刚才存的文件路径
#   pd.read_csv(...) → 让 pandas 去读这个 CSV 文件
#   header=2         → 用第 3 行当列名
#                      （python 数数从 0 开始：第1行=0，第2行=1，第3行=2）
#   df =             → 读出来的表，存进名叫 df 的盒子
#
# df 是 dataframe 的缩写，意思是"数据表"。名字随便起，大家习惯叫 df


print(df.shape)
# shape = 形状，也就是"几行几列"
# 输出 (19, 3) 表示 19 行、3 列


print(df.head())
# head() = 给我看前 5 行
# 想看前 10 行就写 head(10)


print(df.dtypes)
# dtypes = data types，每一列是什么类型
# object  = 文本（哪怕里面写着数字）
# float64 = 小数（真正能参与计算的数字）


# ------------------------------------------------------------
# 第二段：把重复行找出来、删掉
# ------------------------------------------------------------

print(df[df.duplicated(keep=False)])
# 从里往外读：
#   df.duplicated()      → 给每一行打标记：和前面某行完全一样就标 True
#   keep=False           → 不加这个，只标"后出现的那条"；
#                          加上它，两条重复的都标出来，你才看得见是哪两个
#   df[一堆True/False]   → 只把标 True 的行显示出来
#
# 这个写法叫"布尔索引"，整张表里最常用的筛选方式：
#   方括号里放一串 True/False，就是"留下 True 的行"


df = df.drop_duplicates()
# drop_duplicates() = 删掉重复行，只留第一次出现的那条
#
# ★ df = 这三个字绝对不能省 ★
#   不写 df = ，它只是"生成一张新表"然后扔掉，原表一点没变
#   写上 df = ，才是"用新表替换掉旧表"
#
# 一句话记住：pandas 的操作默认不改原表，要接住它的返回值


print(df.shape)
# 现在应该变成 (18, 3)


# ------------------------------------------------------------
# 第三段：把"看着像数字的文本"变成真数字
# ------------------------------------------------------------

df["GDP"] = df["GDP"].str.replace(",", "").astype(float)
# 这行最长，但只要从左往右一环一环看就不难：
#
#   df["GDP"]                 从表里取出 GDP 这一列
#   .str                      声明"接下来按文本方式处理"
#   .replace(",", "")         把逗号换成空 → "13,617.8" 变成 "13617.8"
#   .astype(float)            强行转成小数 → 13617.8
#   df["GDP"] =               把结果存回 GDP 这一列
#
# 为什么非要转？因为 "13,617.8" 里有逗号，pandas 只能当它是一句话，
# 一句话是不能求平均、不能排序的


df["增速(%)"] = pd.to_numeric(df["增速(%)"], errors="coerce")
# 这行的写法不一样：不是链式，是"把一列塞进一个函数里"
#
#   df["增速(%)"]                取出增速这一列
#   pd.to_numeric(..., errors="coerce")
#                                转成数字；转不了的直接标成空，不报错
#   errors="coerce"              这个参数就是"别报错，标成空"的意思
#
# 转完之后，那两个 "—" 才变成真正的空值 NaN（NaN = 没有数字）
# 在此之前，"—" 是个普通字符，程序看不出它是"缺数据"


print(df.dtypes)
# 现在 GDP 和 增速(%) 都该是 float64 了


print(df.isna().sum())
#   df.isna()     → 每个格子是空的吗？True/False
#   .sum()        → 数一数每列有几个 True
# 输出里 增速(%) 那列是 2，意思是缺了 2 个


print(df[df["增速(%)"].isna()])
# 和上面 duplicated 一个套路：
#   df["增速(%)"].isna()  → 这一列哪些是空的
#   df[上面那串True/False] → 只显示这些行
# 结果会告诉你是三门峡市和济源市


# ------------------------------------------------------------
# 第四段：算一下，然后存出去
# ------------------------------------------------------------

print(df["GDP"].mean())
# mean() = 平均值
# pandas 算平均时会自动跳过 NaN，不会因为有空值就整列作废


print(df.sort_values("GDP", ascending=False).head(3))
#   sort_values("GDP")           → 按 GDP 这一列排序
#   ascending=False              → False 就是"不升序"，即降序（大到小）
#   .head(3)                     → 排完只要前 3 行
# 连着写就是"先排序，再从结果里取前 3 行"


df.to_csv(r"data\henan_clean.csv", index=False, encoding="utf-8-sig")
# to_csv = 存成 CSV 文件
#   index=False        → 不要把行号(0,1,2...)写进文件
#                        不写这个，存出来会多一列没用的数字
#   encoding="utf-8-sig" → 让 Excel 打开时中文不乱码


# ============================================================
# 附：把一条长链拆开写
#
# 上面那句 GDP 是"链式写法"，一行干四件事。
# 下面把它拆成五步，结果完全一样。
# 看不懂长链的时候，就在脑子里这样拆。
# ============================================================

# 原句：
#   df["GDP"] = df["GDP"].str.replace(",", "").astype(float)
#
# ★ 先看一个真实的坑 ★
# 上面第 12 行已经跑过一次了，所以此刻 df["GDP"] 已经是数字（float64），
# 不再是文本。如果你现在再对它写 .str，会直接报错：
#
#   AttributeError: Can only use .str accessor with string values!
#
# 报错的意思是：.str 只能用在"文本列"上，数字列不能按文本处理。
#
# 所以下面重新从脏文件读一份出来，当作"还没洗过的表"，
# 再把它一步一步拆开走一遍。每一步都打印出来，你能看见值在变。

demo = pd.read_csv(r"data\henan_dirty.csv", header=2)
demo = demo.drop_duplicates()

# 第一步：取出这一列，放进一个临时盒子
tmp = demo["GDP"]
print("第一步之后:", tmp.head(2).tolist())

# 第二步：声明按文本处理（相当于告诉 pandas：接下来的动作按"文本"来理解）
tmp = tmp.str

# 第三步：逗号换成空
tmp = tmp.replace(",", "")
print("第三步之后:", tmp.head(2).tolist())

# 第四步：转成小数
tmp = tmp.astype(float)
print("第四步之后:", tmp.head(2).tolist())

# 第五步：存回表里
demo["GDP"] = tmp
print("第五步之后:", demo["GDP"].head(2).tolist())

# 结论：链式写法只是"把每一步的结果直接递给下一步"的简写，
#       没有任何神秘的地方。. 后面每加一段，就是对上一个结果再做一件事。
#
# 顺带记住这个教训：
#   报错不是"你完蛋了"，是 python 在告诉你"这一步的前提不满足"。
#   看到报错先读最后一行 —— 它几乎总是把原因写清楚了。
